#!/bin/bash
# Example PBS submission script for the historical a_lm stage (compute_coeff<i>.py).
# Edit the placeholders before use.  For new work the one-pass pipeline
# (python -m Eig_ULDM_packages.pipeline, see examples/pbs and examples/slurm)
# replaces this whole stage.
set -euo pipefail

# ---- User settings (edit these) ----
WORK_DIR="/path/to/Outputs"           # PyUL run Outputs/ directory (holds 3WfnRS/ and r0_segment*.npy)
ENV_NAME="your_conda_env"             # Conda environment to activate (leave empty to skip conda)

# IMPORTANT:
#   The compute_coeff<i>.py scripts and r0_segment<i>.npy files are generated by
#   Step 1 of Main.ipynb (compute_coeff<i>.py next to the notebook, r0_segment<i>.npy in WORK_DIR).
#   JOB_COUNT must equal the number of segments (n_segments in Main.ipynb).
JOB_COUNT=4                            # Number of jobs / script shards (match r0 segments)

# Extra options for compute_coeff<i>.py, e.g. the 3WfnRS box for PyUL <= 30.40 runs:
COEFF_ARGS="--rs-length-kpc 5.0 --rs-resol 256"

# Optional: pin each job to a specific node (one node per job). Leave empty (the default)
# to let the scheduler choose.
NODE_LIST=()                           # e.g. (m33 m34 m37 m39)

NCPUS=56                               # CPU cores per job
WALLTIME="24:00:00"                   # Job walltime (HH:MM:SS)
QUEUE=""                              # Queue name (optional; leave empty to omit)

# ---- Derived paths ----
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
STAMP="$(date +%Y%m%d_%H%M%S)"
LOG_DIR="${WORK_DIR}/logs"
JOB_DIR="${WORK_DIR}/pbs_jobs_${STAMP}"   # generated job scripts are kept for provenance

command -v qsub >/dev/null 2>&1 || { echo "error: qsub not found (this script is for PBS)" >&2; exit 1; }
[ -d "${WORK_DIR}" ] || { echo "error: WORK_DIR ${WORK_DIR} does not exist" >&2; exit 1; }
mkdir -p "${LOG_DIR}" "${JOB_DIR}"

# Check all inputs before submitting anything
for i in $(seq 1 "${JOB_COUNT}"); do
    [ -f "${SCRIPT_DIR}/compute_coeff${i}.py" ] || { echo "error: ${SCRIPT_DIR}/compute_coeff${i}.py missing (run Main.ipynb Step 1)" >&2; exit 1; }
    [ -f "${WORK_DIR}/r0_segment${i}.npy" ] || { echo "error: ${WORK_DIR}/r0_segment${i}.npy missing (run Main.ipynb Step 1)" >&2; exit 1; }
done

for i in $(seq 1 "${JOB_COUNT}"); do
    NODE=""
    if [ "${#NODE_LIST[@]}" -ge "${i}" ]; then
        NODE="${NODE_LIST[$((i-1))]}"
    fi
    JOB="${JOB_DIR}/submit_job${i}.pbs"

    cat > "${JOB}" << EOF
#!/bin/bash
#PBS -N ULDM_coeff${i}
#PBS -l walltime=${WALLTIME}
#PBS -j oe
#PBS -o ${LOG_DIR}/ULDM_coeff${i}_${STAMP}.log
EOF
    if [ -n "${NODE}" ]; then
        echo "#PBS -l select=1:ncpus=${NCPUS}:host=${NODE}" >> "${JOB}"
    else
        echo "#PBS -l select=1:ncpus=${NCPUS}" >> "${JOB}"
    fi
    if [ -n "${QUEUE}" ]; then
        echo "#PBS -q ${QUEUE}" >> "${JOB}"
    fi

    cat >> "${JOB}" << EOF

set -euo pipefail
cd "${WORK_DIR}"

# Load environment (edit if you use something other than conda); set -u relaxed for rc files
if [ -n "${ENV_NAME}" ]; then
    set +u
    source ~/.bashrc
    eval "\$(conda shell.bash hook)"
    conda activate "${ENV_NAME}"
    set -u
fi

export PYTHONUNBUFFERED=1
export OMP_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 MKL_NUM_THREADS=1

# Run the script from SCRIPT_DIR while keeping WORK_DIR as the cwd. The generated
# compute_coeff${i}.py is kept (provenance, requeue); failures give a non-zero exit code.
python3 -u "${SCRIPT_DIR}/compute_coeff${i}.py" ${COEFF_ARGS}
EOF

    echo "Submitting job ${i}..."
    if ! JOBID="$(qsub "${JOB}")"; then
        echo "error: qsub failed for ${JOB}" >&2
        exit 1
    fi
    echo "Job ${i} submitted: ${JOBID} (script kept at ${JOB})"
done

echo "All jobs submitted."
